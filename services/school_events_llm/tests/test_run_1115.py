import unittest

from app.generation.humanize import drop_meta_notes
from app.generation.ids import content_to_text
from app.validation.inner_timing import inner_timing_problems

# Карточки героев (День защитника Отечества, 8 класс), как их прислала модель; истории сокращены.
HERO_CARDS = [
    {"hero_name": "Анна Сергеевна", "story": "Анна Сергеевна работает медсестрой. Благодаря ей пациента удалось спасти.",
     "qualities": "ответственность, чуткость, оперативность"},
    {"hero_name": "Сергей Викторович", "story": "Сергей Викторович - пожарный. Он трижды заходил в горящий дом.",
     "qualities": "смелость, самоотверженность"},
]

# Блок «Создание информационного стенда» (Народы Среднего Урала, 10 класс, 4 команды, 10 мин), реплика из трассы.
STAND_BLOCK = """Педагог обращается ко всему классу:

«Ребята, сейчас мы создадим наш общий информационный стенд. Давайте разделимся на четыре рабочие зоны - каждая команда займётся оформлением своего раздела. Вам понадобятся бумага, маркеры и цветные карандаши. Помните, что наша главная цель - представить разнообразие культур Среднего Урала интересно и наглядно.

На оформление каждой команде даётся примерно семь минут. Затем у нас останется пара минут, чтобы посмотреть готовый стенд вместе. Начинайте!

Через шесть минут педагог предупреждает:

«Осталась одна минута, завершайте оформление!»"""


class ContentLabelsTest(unittest.TestCase):
    def test_hero_cards(self):
        """Имя героя - заголовок пункта, остальные подписи по-русски, без «.;» на стыке."""
        self.assertEqual(content_to_text(HERO_CARDS),
                         "1. Анна Сергеевна. История: Анна Сергеевна работает медсестрой. Благодаря ей пациента удалось спасти. "
                         "Качества: ответственность, чуткость, оперативность\n"
                         "2. Сергей Викторович. История: Сергей Викторович - пожарный. Он трижды заходил в горящий дом. "
                         "Качества: смелость, самоотверженность")

    def test_topic_cards(self):
        content = [{"theme": "Традиции народов Среднего Урала"}, {"theme": "Языки народов Среднего Урала"}]
        self.assertEqual(content_to_text(content), "1. Тема: Традиции народов Среднего Урала\n2. Тема: Языки народов Среднего Урала")

    def test_unknown_english_key_dropped_russian_kept(self):
        """Незнакомый английский ключ не показывается, значение остаётся; русские ключи модели - как есть."""
        self.assertEqual(content_to_text([{"name": "Станция 1", "fun_fact": "Урал - граница Европы и Азии"}]),
                         "1. Название: Станция 1; Урал - граница Европы и Азии")
        self.assertEqual(content_to_text([{"Критерий": "Идея", "Максимум баллов": 5}]), "1. Критерий: Идея; Максимум баллов: 5")
        self.assertEqual(content_to_text({"theme": "Ремёсла", "extra_info": "Каслинское литьё"}), "Тема: Ремёсла\nКаслинское литьё")

    def test_labels_in_plain_text(self):
        """Те же подписи, если модель написала их прямо в тексте материала."""
        variant = {"timeline": [], "teacher_instructions": [],
                   "materials": [{"material_id": "topic_cards", "content": "1. theme: Традиции народов\n2. theme: Языки народов",
                                  "teacher_notes": ""}]}
        drop_meta_notes(variant)
        self.assertEqual(variant["materials"][0]["content"], "1. Тема: Традиции народов\n2. Тема: Языки народов")


class WorkTimeIsNotPresentationTest(unittest.TestCase):
    @staticmethod
    def problems(text, duration=10, groups=4):
        return inner_timing_problems({"duration_minutes": duration, "teacher_script": text, "pupil_actions": []},
                                     groups_count=groups, pairs_count=0)

    def test_stand_block(self):
        """Команды оформляют свои разделы одновременно: это не 4 выступления по 7 минут."""
        self.assertEqual(self.problems(STAND_BLOCK), [])

    def test_work_purposes(self):
        for text in ("Каждая группа представит плакат. На подготовку каждой группе даётся 6 минут.",
                     "На выполнение задания каждой команде даётся 8 минут, потом покажете результат."):
            with self.subTest(text=text):
                self.assertEqual(self.problems(text), [])

    def test_presentation_time_still_flagged(self):
        """Время на само выступление по-прежнему считается: 4 команды × 7 минут в 10-минутном блоке."""
        self.assertEqual(self.problems("Каждая команда представит свой раздел стенда. На выступление каждой команде даётся 7 минут."),
                         ["выступления: 4 групп × 7 мин = 28 мин, а на блок 10 мин"])


